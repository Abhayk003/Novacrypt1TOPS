//==============================================================================
// proc_coverage.sv
//
// Two coverage sources, kept deliberately separate because they answer
// different questions:
//
//   1. Bus-behavior covergroups, sampled from the (blackbox-legitimate)
//      AXI monitors: read/write mix, AXI response codes actually seen,
//      instruction-fetch burst addresses, address regions touched. This
//      is a true DUT-observed coverage model.
//
//   2. Instruction-variant coverage, sampled from the golden model's
//      per-retired-instruction pc trace (golden/gen_golden.py's
//      pc_trace_file). This is "did this test *ask* the core to
//      exercise opcode X" coverage, not "did we *prove* the core
//      executed opcode X correctly" -- that correctness claim is the
//      scoreboard's job (indirectly, via memory side effects). Per-
//      instruction retirement simply isn't observable at top_module's
//      port list, so this is the best available proxy for "did our
//      regression suite's instruction mix hit every variant" tracking.
//      Clearly labeled as such in the coverage report (see cg_variant)
//==============================================================================
class proc_coverage extends uvm_subscriber #(proc_pkg::proc_data_txn);
  `uvm_component_utils(proc_coverage)

  proc_pkg::proc_env_cfg cfg;

  proc_pkg::proc_data_txn data_txn;
  proc_pkg::proc_instr_txn instr_txn;
  uvm_analysis_imp_instr #(proc_pkg::proc_instr_txn, proc_coverage) instr_imp;
  uvm_analysis_imp_golden #(proc_pkg::proc_golden_txn, proc_coverage) golden_imp;
  uvm_analysis_imp_irq #(proc_pkg::proc_irq_txn, proc_coverage) irq_imp;
  proc_pkg::proc_irq_txn irq_txn;
  bit [2:0] irq_levels_seen;
  bit [1:0] irq_line_cp;
  bit irq_value_cp;
  bit irq_atomic_cp;
  bit [2:0] irq_state_cp;


  typedef enum int {
    DATA_REGION_DMEM,
    DATA_REGION_OTHER
  } data_region_e;

  typedef enum int {
    STORE_SB_LANE0,
    STORE_SB_LANE1,
    STORE_SB_LANE2,
    STORE_SB_LANE3,
    STORE_SH_LOW,
    STORE_SH_HIGH,
    STORE_SW,
    STORE_ILLEGAL
  } store_kind_e;

  data_region_e data_region;
  store_kind_e  store_kind;

  // Classify the address into architecturally meaningful regions.
  function automatic data_region_e get_data_region(bit [31:0] addr);
    if ((addr >= proc_pkg::DMEM_BASE) &&
        (addr <= proc_pkg::DMEM_LIMIT))
      return DATA_REGION_DMEM;
    else
      return DATA_REGION_OTHER;
  endfunction

  // Classify an observed AXI WSTRB pattern.
  //
  // These are the patterns generated by the RV32I store operations
  // implemented by the DUT.
  function automatic store_kind_e get_store_kind(bit [3:0] strb);
    case (strb)
      4'b0001: return STORE_SB_LANE0;
      4'b0010: return STORE_SB_LANE1;
      4'b0100: return STORE_SB_LANE2;
      4'b1000: return STORE_SB_LANE3;

      4'b0011: return STORE_SH_LOW;
      4'b1100: return STORE_SH_HIGH;

      4'b1111: return STORE_SW;

      default:  return STORE_ILLEGAL;
    endcase
  endfunction


covergroup cg_data_bus;
  option.per_instance = 1;

  cp_dir: coverpoint data_txn.dir {
    bins read  = {proc_pkg::DATA_READ};
    bins write = {proc_pkg::DATA_WRITE};
  }

  cp_resp: coverpoint data_txn.resp {
    bins okay   = {proc_pkg::AXI_OKAY};
    //bins slverr = {proc_pkg::AXI_SLVERR}; - slave error, does dut generate?
  }

  cp_align: coverpoint data_txn.addr[1:0] {
    bins word_aligned = {2'b00};
    bins offset_1     = {2'b01};
    bins offset_2     = {2'b10};
    bins offset_3     = {2'b11};
  }

  cp_wstrb: coverpoint data_txn.wstrb
    iff (data_txn.dir == proc_pkg::DATA_WRITE) {
    bins byte0         = {4'b0001};
    bins byte1         = {4'b0010};
    bins byte2         = {4'b0100};
    bins byte3         = {4'b1000};
    bins halfword_low  = {4'b0011};
    bins halfword_high = {4'b1100};
    bins word          = {4'b1111};
  }

  cx_dir_resp: cross cp_dir, cp_resp;
  cx_dir_align: cross cp_dir, cp_align;

endgroup

typedef enum int {
  INSTR_BOOT_ROM,
  INSTR_IMEM,
  INSTR_INVALID
} instr_region_e;

instr_region_e instr_region;

proc_pkg::axi_resp_e instr_resp;

int unsigned instr_beat_count;

bit instr_rlast_seen;

covergroup cg_instr_bus;
  option.per_instance = 1;

  // ------------------------------------------------------------
  // FETCH REGION
  // ------------------------------------------------------------
  // Cover the address of the AR request, not "boot ROM vs not
  // boot ROM".  Non-ROM is NOT automatically IMEM.
  //
  // Legal instruction fetch regions for this DUT:
  //   Boot ROM : 0x0000_0000 - 0x0000_3FFF
  //   IMEM     : 0x0001_0000 - 0x0001_FFFF
  // ------------------------------------------------------------
  cp_region: coverpoint instr_region {
    bins boot_rom = {INSTR_BOOT_ROM};
    //below disabled for cpu testing, should be enabled for soc
    //bins imem     = {INSTR_IMEM};
    //bins invalid  = {INSTR_INVALID};
  }

  // ------------------------------------------------------------
  // AXI RESPONSE
  // ------------------------------------------------------------
  cp_resp: coverpoint instr_resp {
    bins okay    = {proc_pkg::AXI_OKAY};
    //bins exokay  = {proc_pkg::AXI_EXOKAY};
    //bins slverr  = {proc_pkg::AXI_SLVERR};
    //bins decerr  = {proc_pkg::AXI_DECERR};
  }

  // ------------------------------------------------------------
  // BURST LENGTH
  // ARLEN is beats-1.
  // Your current DUT uses 4-beat instruction bursts, therefore
  // ARLEN == 3 is the expected normal case.
  // ------------------------------------------------------------
  cp_burst_len: coverpoint instr_txn.arlen {
    bins four_beats = {3};
    bins other      = default;
  }

  // ------------------------------------------------------------
  // BURST TYPE
  // AXI:
  //   FIXED = 2'b00
  //   INCR  = 2'b01
  //   WRAP  = 2'b10
  //   reserved = 2'b11
  // ------------------------------------------------------------
  cp_burst_type: coverpoint instr_txn.arburst {
    bins incr  = {2'b01};
    illegal_bins illegal  = {2'b11};
  }

  // ------------------------------------------------------------
  // TRANSFER SIZE
  // 2'b010 = 4 bytes = 32-bit instruction word.
  // ------------------------------------------------------------
  cp_burst_size: coverpoint instr_txn.arsize {
    bins byte4 = {2};
    bins other = default;
  }

  // ------------------------------------------------------------
  // DID THE MONITOR RECEIVE THE EXPECTED NUMBER OF BEATS?
  // ------------------------------------------------------------
  cp_beat_count: coverpoint instr_beat_count {
    bins four  = {4};
    bins other = default;
  }

  // ------------------------------------------------------------
  // RLAST / BURST COMPLETION
  // ------------------------------------------------------------
  cp_rlast: coverpoint instr_rlast_seen {
    bins seen    = {1};
    illegal_bins missing = {0};
  }

  // ------------------------------------------------------------
  // Useful crosses
  // ------------------------------------------------------------
  cx_region_resp: cross cp_region, cp_resp;

  cx_region_burst: cross cp_region, cp_burst_len;

  cx_burst_resp: cross cp_burst_len, cp_resp;
endgroup

  covergroup cg_irq;
    option.per_instance = 1;
    cp_line: coverpoint irq_line_cp iff (!irq_atomic_cp) {
      bins timer = {0};
      bins software = {1};
      bins external = {2};
    }
    cp_value: coverpoint irq_value_cp iff (!irq_atomic_cp) {
      bins irq_asserted   = {1};
      bins irq_deasserted = {0};
    }
    cp_atomic: coverpoint irq_atomic_cp {
      bins individual = {0};
      bins simultaneous_update = {1};
    }
    cp_levels: coverpoint irq_state_cp {
      bins none = {3'b000};
      bins timer_only = {3'b001};
      bins software_only = {3'b010};
      bins external_only = {3'b100};
      bins two_or_more = {3'b011,3'b101,3'b110,3'b111};
    }
    cx_line_value: cross cp_line, cp_value;
  endgroup

  function new(string name, uvm_component parent);
    super.new(name, parent);
    cg_data_bus  = new();
    cg_instr_bus = new();
    cg_variant   = new();
    cg_irq       = new();
    instr_imp    = new("instr_imp", this);
    golden_imp   = new("golden_imp", this);
    irq_imp      = new("irq_imp", this);
    irq_levels_seen = 3'b000;
  endfunction

  function void build_phase(uvm_phase phase);
    super.build_phase(phase);
    if (!uvm_config_db#(proc_pkg::proc_env_cfg)::get(this, "", "cfg", cfg))
      `uvm_fatal("PROC_COV", "env cfg not set")
  endfunction

  // uvm_subscriber's required override -- data-bus side.
  function void write(proc_pkg::proc_data_txn t);
    data_txn = t;
    cg_data_bus.sample();
  endfunction

  // Second analysis export -- instruction-bus side.
function void write_instr(proc_pkg::proc_instr_txn t);
  int i;
//`uvm_info("PROC_COV",
//          $sformatf("write_instr CALLED: araddr=%08h rdata_size=%0d",
//                    t.araddr, t.rdata.size()),
//          UVM_LOW)
  if (t.rresp.size() == 0)
    return;

  instr_txn = t;

  // ------------------------------------------------------------
  // Determine actual fetch region.
  // ------------------------------------------------------------
  if ((t.araddr >= proc_pkg::BOOT_ROM_BASE) &&
      (t.araddr <= proc_pkg::BOOT_ROM_LIMIT)) begin

    instr_region = INSTR_BOOT_ROM;

  end
  else if ((t.araddr >= proc_pkg::IMEM_BASE) &&
           (t.araddr <= proc_pkg::IMEM_LIMIT)) begin

    instr_region = INSTR_IMEM;

  end
  else begin

    instr_region = INSTR_INVALID;

  end

  // ------------------------------------------------------------
  // Burst-level information.
  // ------------------------------------------------------------
  instr_beat_count = t.rdata.size();

  // Monitor terminates the transaction only when RLAST is seen.
  // Therefore a completed proc_instr_txn means RLAST was observed.
  instr_rlast_seen = 1'b1;

  // ------------------------------------------------------------
  // Sample every response beat, not just rresp[0].
  //
  // Region/burst information remains constant for the burst,
  // while response changes per beat.
  // ------------------------------------------------------------
  for (i = 0; i < t.rresp.size(); i++) begin
    instr_resp = t.rresp[i];
    cg_instr_bus.sample();
  end

  // ------------------------------------------------------------
  // Instruction encoding coverage is also sampled from the
  // DUT-observed RDATA.
  // ------------------------------------------------------------
  for (i = 0; i < t.rdata.size(); i++) begin
    instr_variant = decode_rv32im(t.rdata[i]);
    cg_variant.sample();
  end
endfunction
  

function void write_irq(proc_pkg::proc_irq_txn t);
  irq_txn = t;
  irq_atomic_cp = t.atomic_levels;
  if (t.atomic_levels) begin
    irq_levels_seen = t.levels;
    irq_line_cp = 0;
    irq_value_cp = t.levels[0];
  end
  else begin
    irq_line_cp = t.line;
    irq_value_cp = t.value;
    case (t.line)
      proc_pkg::IRQ_TIMER:    irq_levels_seen[0] = t.value;
      proc_pkg::IRQ_SOFTWARE: irq_levels_seen[1] = t.value;
      proc_pkg::IRQ_EXTERNAL: irq_levels_seen[2] = t.value;
      default: ;
    endcase
  end
  irq_state_cp = irq_levels_seen;
  cg_irq.sample();
endfunction

function void write_golden(proc_pkg::proc_golden_txn t);
  // Golden model is no longer the source for instruction
  // functional coverage.
  //
  // cg_variant is sampled from DUT-observed instruction AXI
  // RDATA inside write_instr().
endfunction

 //============================================================================
// DUT-observed RV32IM instruction coverage.
//
// instr_word comes directly from the instruction AXI RDATA observed by
// axi_instr_monitor.  We classify only architecturally meaningful RV32IM
// encodings.  Reserved funct3/funct7 combinations are NOT coverage bins.
// ============================================================================

typedef enum int unsigned {
  V_ILLEGAL,

  // RV32I upper/immediate/control
  V_LUI,
  V_AUIPC,
  V_JAL,
  V_JALR,

  // RV32I branches
  V_BEQ,
  V_BNE,
  V_BLT,
  V_BGE,
  V_BLTU,
  V_BGEU,

  // RV32I loads
  V_LB,
  V_LH,
  V_LW,
  V_LBU,
  V_LHU,

  // RV32I stores
  V_SB,
  V_SH,
  V_SW,

  // RV32I immediate ALU
  V_ADDI,
  V_SLLI,
  V_SLTI,
  V_SLTIU,
  V_XORI,
  V_SRLI,
  V_SRAI,
  V_ORI,
  V_ANDI,

  // RV32I register ALU
  V_ADD,
  V_SUB,
  V_SLL,
  V_SLT,
  V_SLTU,
  V_XOR,
  V_SRL,
  V_SRA,
  V_OR,
  V_AND,

  // RV32M
  V_MUL,
  V_MULH,
  V_MULHSU,
  V_MULHU,
  V_DIV,
  V_DIVU,
  V_REM,
  V_REMU,

  // RV32I memory/system
  V_FENCE,
  V_ECALL,
  V_EBREAK
} rv32im_variant_e;

rv32im_variant_e instr_variant;

function automatic rv32im_variant_e decode_rv32im(bit [31:0] ins);

  bit [6:0] opcode;
  bit [2:0] funct3;
  bit [6:0] funct7;

  opcode = ins[6:0];
  funct3 = ins[14:12];
  funct7 = ins[31:25];

  decode_rv32im = V_ILLEGAL;

  case (opcode)
    7'b0110111:
      decode_rv32im = V_LUI;

    // ----------------------------------------------------------
    // AUIPC
    // ----------------------------------------------------------
    7'b0010111:
      decode_rv32im = V_AUIPC;

    // ----------------------------------------------------------
    // JAL
    // ----------------------------------------------------------
    7'b1101111:
      decode_rv32im = V_JAL;

    // ----------------------------------------------------------
    // JALR
    // funct3 must be 000
    // ----------------------------------------------------------
    7'b1100111:
      if (funct3 == 3'b000)
        decode_rv32im = V_JALR;

    // ----------------------------------------------------------
    // BRANCH
    // ----------------------------------------------------------
    7'b1100011: begin
      case (funct3)
        3'b000: decode_rv32im = V_BEQ;
        3'b001: decode_rv32im = V_BNE;
        3'b100: decode_rv32im = V_BLT;
        3'b101: decode_rv32im = V_BGE;
        3'b110: decode_rv32im = V_BLTU;
        3'b111: decode_rv32im = V_BGEU;
        default: decode_rv32im = V_ILLEGAL;
      endcase
    end

    // ----------------------------------------------------------
    // LOAD
    // ----------------------------------------------------------
    7'b0000011: begin
      case (funct3)
        3'b000: decode_rv32im = V_LB;
        3'b001: decode_rv32im = V_LH;
        3'b010: decode_rv32im = V_LW;
        3'b100: decode_rv32im = V_LBU;
        3'b101: decode_rv32im = V_LHU;
        default: decode_rv32im = V_ILLEGAL;
      endcase
    end

    // ----------------------------------------------------------
    // STORE
    // ----------------------------------------------------------
    7'b0100011: begin
      case (funct3)
        3'b000: decode_rv32im = V_SB;
        3'b001: decode_rv32im = V_SH;
        3'b010: decode_rv32im = V_SW;
        default: decode_rv32im = V_ILLEGAL;
      endcase
    end

    // ----------------------------------------------------------
    // OP-IMM
    // ----------------------------------------------------------
    7'b0010011: begin
      case (funct3)

        3'b000:
          decode_rv32im = V_ADDI;

        3'b001:
          if (funct7 == 7'b0000000)
            decode_rv32im = V_SLLI;

        3'b010:
          decode_rv32im = V_SLTI;

        3'b011:
          decode_rv32im = V_SLTIU;

        3'b100:
          decode_rv32im = V_XORI;

        3'b101: begin
          if (funct7 == 7'b0000000)
            decode_rv32im = V_SRLI;
          else if (funct7 == 7'b0100000)
            decode_rv32im = V_SRAI;
        end

        3'b110:
          decode_rv32im = V_ORI;

        3'b111:
          decode_rv32im = V_ANDI;

        default:
          decode_rv32im = V_ILLEGAL;

      endcase
    end

    // ----------------------------------------------------------
    // OP / OP-M
    // ----------------------------------------------------------
    7'b0110011: begin

      case (funct7)

        // ----------------------------
        // RV32I register ALU
        // ----------------------------
        7'b0000000: begin
          case (funct3)
            3'b000: decode_rv32im = V_ADD;
            3'b001: decode_rv32im = V_SLL;
            3'b010: decode_rv32im = V_SLT;
            3'b011: decode_rv32im = V_SLTU;
            3'b100: decode_rv32im = V_XOR;
            3'b101: decode_rv32im = V_SRL;
            3'b110: decode_rv32im = V_OR;
            3'b111: decode_rv32im = V_AND;
            default: decode_rv32im = V_ILLEGAL;
          endcase
        end

        // ----------------------------
        // SUB / SRA
        // ----------------------------
        7'b0100000: begin
          case (funct3)
            3'b000: decode_rv32im = V_SUB;
            3'b101: decode_rv32im = V_SRA;
            default: decode_rv32im = V_ILLEGAL;
          endcase
        end

        // ----------------------------
        // RV32M
        // ----------------------------
        7'b0000001: begin
          case (funct3)
            3'b000: decode_rv32im = V_MUL;
            3'b001: decode_rv32im = V_MULH;
            3'b010: decode_rv32im = V_MULHSU;
            3'b011: decode_rv32im = V_MULHU;
            3'b100: decode_rv32im = V_DIV;
            3'b101: decode_rv32im = V_DIVU;
            3'b110: decode_rv32im = V_REM;
            3'b111: decode_rv32im = V_REMU;
            default: decode_rv32im = V_ILLEGAL;
          endcase
        end

        default:
          decode_rv32im = V_ILLEGAL;

      endcase
    end

    // ----------------------------------------------------------
    // FENCE
    // ----------------------------------------------------------
    7'b0001111:
      if (funct3 == 3'b000)
        decode_rv32im = V_FENCE;

    // ----------------------------------------------------------
    // SYSTEM
    // ECALL / EBREAK
    //
    // ECALL = 0x00000073
    // EBREAK = 0x00100073
    // ----------------------------------------------------------
    7'b1110011: begin

      if (ins == 32'h00000073)
        decode_rv32im = V_ECALL;

      else if (ins == 32'h00100073)
        decode_rv32im = V_EBREAK;

    end

    default:
      decode_rv32im = V_ILLEGAL;

  endcase

endfunction

covergroup cg_variant;
  option.per_instance = 1;

  cp_variant: coverpoint instr_variant {

    bins lui      = {V_LUI};
    bins auipc    = {V_AUIPC};
    bins jal      = {V_JAL};
    bins jalr     = {V_JALR};

    bins beq      = {V_BEQ};
    bins bne      = {V_BNE};
    bins blt      = {V_BLT};
    bins bge      = {V_BGE};
    bins bltu     = {V_BLTU};
    bins bgeu     = {V_BGEU};

    bins lb       = {V_LB};
    bins lh       = {V_LH};
    bins lw       = {V_LW};
    bins lbu      = {V_LBU};
    bins lhu      = {V_LHU};

    bins sb       = {V_SB};
    bins sh       = {V_SH};
    bins sw       = {V_SW};

    bins addi     = {V_ADDI};
    bins slli     = {V_SLLI};
    bins slti     = {V_SLTI};
    bins sltiu    = {V_SLTIU};
    bins xori     = {V_XORI};
    bins srli     = {V_SRLI};
    bins srai     = {V_SRAI};
    bins ori      = {V_ORI};
    bins andi     = {V_ANDI};

    bins add      = {V_ADD};
    bins sub      = {V_SUB};
    bins sll      = {V_SLL};
    bins slt      = {V_SLT};
    bins sltu     = {V_SLTU};
    bins xor_op   = {V_XOR};
    bins srl      = {V_SRL};
    bins sra      = {V_SRA};
    bins and_op   = {V_AND};

    bins mul      = {V_MUL};
    bins mulh     = {V_MULH};
    bins mulhsu   = {V_MULHSU};
    bins mulhu    = {V_MULHU};
    bins div      = {V_DIV};
    bins divu     = {V_DIVU};
    bins rem      = {V_REM};
    bins remu     = {V_REMU};

    bins fence    = {V_FENCE};
    bins ecall    = {V_ECALL};
    bins ebreak   = {V_EBREAK};

    // Illegal/reserved encodings are deliberately excluded from
    // functional coverage. They are not meaningful RV32IM variants.
    ignore_bins illegal = {V_ILLEGAL};
  }

endgroup


function void report_phase(uvm_phase phase);

  real cg_cov;
  real cp_cov;

  super.report_phase(phase);

  // ------------------------------------------------------------
  // Functional coverage only
  // ------------------------------------------------------------
  cg_cov = cg_variant.get_inst_coverage();
  cp_cov = cg_variant.cp_variant.get_inst_coverage();

  `uvm_info("FUNC_COV",
    $sformatf("============================================"),
    UVM_NONE)

  `uvm_info("FUNC_COV",
    $sformatf("RV32IM FUNCTIONAL COVERAGE"),
    UVM_NONE)

  `uvm_info("FUNC_COV",
    $sformatf("cg_variant coverage = %0.2f%%", cg_cov),
    UVM_NONE)

  `uvm_info("FUNC_COV",
    $sformatf("cp_variant coverage = %0.2f%%", cp_cov),
    UVM_NONE)

  `uvm_info("FUNC_COV",
    $sformatf("============================================"),
    UVM_NONE)

endfunction

endclass : proc_coverage
